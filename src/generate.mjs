import fs from 'node:fs';
import path from 'node:path';
import { ToolError } from './errors.mjs';
import { hash, json, safePath, writeAtomic, withLock, readJson } from './files.mjs';
import { validate } from './validate.mjs';
import { example } from './example.mjs';
import { sampleScene } from './sample.mjs';

export const VERSION = '0.1.0-dev.1';
const template = name => fs.readFileSync(new URL(`../templates/${name}`, import.meta.url), 'utf8');
const toolLicense = () => fs.readFileSync(new URL('../LICENSE', import.meta.url), 'utf8');
export const sceneHash = scene => hash(JSON.stringify(scene));

export function render(scene) {
  const payload = Buffer.from(JSON.stringify(scene), 'utf8').toString('base64');
  return {
    'THIRD_PARTY_NOTICES/flutter-scene-tool.txt': `This notice applies to code copied from Flutter Scene Tool into this project, including the generated runtime, QA harness, tests, and initial app templates. It does not license your own scene data, assets, or independently authored application code. Preserve this notice with redistributions of the copied source or substantial portions, including binary distributions.\n\n${toolLicense()}`,
    'lib/generated/scene_data.dart': `// Generated by flutter-scene-tool ${VERSION}; edit scene.json instead.\nimport 'dart:convert';\nimport 'scene_runtime.dart';\n\nfinal generatedScene = SceneSpec.fromJson(\n  jsonDecode(utf8.decode(base64Decode('${payload}'))) as Map<String, dynamic>,\n);\n`,
    'lib/generated/scene_runtime.dart': template('scene_runtime.dart'),
    'lib/generated/qa_main.dart': template('qa_main.dart'),
    'test/generated_scene_contract_test.dart': template('scene_contract_test.dart'),
    'test/fixtures/scene_motion_samples.json': json([
      { progress: 0, pointer: [0, 0], scroll: 0, reduced: false },
      { progress: 0.4, pointer: [0.5, -0.5], scroll: 0.6, reduced: false },
      { progress: 1, pointer: [0, 0], scroll: 0, reduced: false },
      { progress: 0.2, pointer: [1, -1], scroll: 1, reduced: true },
    ].map(input => ({ input, expected: sampleScene(scene, input.progress, input).layers }))),
    '.scene-tool/assets.json': json({ schemaVersion: 1, assets: scene.assets.map(asset => asset.path), instruction: 'Declare every listed asset in the user-owned pubspec.yaml before Flutter build. No assets are downloaded or copied.' }),
  };
}

export function emit(root, scene, { dryRun = false } = {}) {
  const validation = validate(scene, { root });
  if (!validation.valid) throw new ToolError('INVALID_SCENE', 'Scene validation failed', validation.errors);
  const files = render(scene);
  const apply = () => {
    const manifestPath = safePath(root, '.scene-tool/generated.json');
    const previous = fs.existsSync(manifestPath) ? readJson(manifestPath) : null;
    if (previous && (previous.schemaVersion !== 1 || typeof previous.files !== 'object' || previous.files === null || Array.isArray(previous.files))) {
      throw new ToolError('MANIFEST_INVALID', 'Generated-file manifest is invalid; restore it before regenerating');
    }
    const changes = [];
    const conflicts = [];
    for (const [name, content] of Object.entries(files)) {
      const target = safePath(root, name);
      const nextHash = hash(content);
      if (fs.existsSync(target)) {
        if (!fs.statSync(target).isFile()) throw new ToolError('OUTPUT_TYPE', `Output is not a regular file: ${name}`);
        const currentHash = hash(fs.readFileSync(target));
        if (currentHash === nextHash) continue;
        if (previous?.files[name] !== currentHash) { conflicts.push({ path: name, code: 'EDIT_CONFLICT', message: 'File is user-modified or untracked; merge it into a user-owned extension or restore the generated version' }); continue; }
      }
      changes.push({ path: name, sha256: nextHash });
    }
    if (conflicts.length) throw new ToolError('EDIT_CONFLICT', 'Generation stopped before writing any files', conflicts, 4);
    const manifest = { schemaVersion: 1, generator: VERSION, sceneHash: sceneHash(scene), files: Object.fromEntries(Object.entries(files).map(([name, bytes]) => [name, hash(bytes)])) };
    // Each replacement is atomic and manifest commits last. A process crash may
    // leave a detectable partial generation; this is not a multi-file transaction.
    if (!dryRun) {
      for (const change of changes) writeAtomic(safePath(root, change.path), files[change.path]);
      if (!previous || json(previous) !== json(manifest)) writeAtomic(manifestPath, json(manifest));
    }
    return { changed: changes, unchanged: Object.keys(files).length - changes.length, dryRun, sceneHash: manifest.sceneHash, warnings: validation.warnings };
  };
  return dryRun ? apply() : withLock(root, apply);
}

export function initProject(directory) {
  const root = path.resolve(directory);
  const parent = path.dirname(root);
  if (!fs.existsSync(parent)) throw new ToolError('PARENT_MISSING', 'Parent directory must exist');
  // Refuse symlink ancestry; no unreviewed project can redirect writes elsewhere.
  let current = path.parse(parent).root;
  for (const part of parent.slice(current.length).split(path.sep).filter(Boolean)) {
    current = path.join(current, part);
    if (fs.lstatSync(current).isSymbolicLink()) throw new ToolError('SYMLINK_PATH', 'Project parent cannot contain symlinks. Use its canonical path, such as /private/tmp on macOS');
  }
  if (fs.existsSync(root)) throw new ToolError('PROJECT_EXISTS', 'init requires a new directory and never overwrites an existing project');
  fs.mkdirSync(root);
  const files = {
    'scene.json': json(example),
    'lib/main.dart': template('main.dart'),
    'lib/custom_scene.dart': template('custom_scene.dart'),
    'web/index.html': template('index.html'),
    'pubspec.yaml': "name: editable_scene\ndescription: An editable scene authored with flutter-scene-tool.\npublish_to: none\nversion: 0.1.0+1\nenvironment:\n  sdk: '>=3.13.0 <4.0.0'\n  flutter: '>=3.47.9'\ndependencies:\n  flutter:\n    sdk: flutter\ndev_dependencies:\n  flutter_test:\n    sdk: flutter\nflutter:\n  uses-material-design: true\n",
    'README.md': '# Editable scene\n\nEdit scene.json, then run scene-tool emit scene.json. Put custom Flutter UI in lib/custom_scene.dart. Generated files are hash-guarded.\n\nA minimal user-owned web/index.html bootstrap is included. With Flutter installed, run `flutter pub get`, `flutter analyze`, `flutter test`, and `flutter build web --release --no-web-resources-cdn`. Native platform shells are not generated.\n\nWhen adding images, declare the exact asset paths listed in .scene-tool/assets.json in pubspec.yaml. No source artwork is bundled. The abstract seed is a contract fixture, not a finished visual design.\n\nPreserve THIRD_PARTY_NOTICES/flutter-scene-tool.txt when redistributing copied tool code, including binary distributions. It covers the copied MIT-licensed runtime/templates only, not your original application, scene data, or assets.\n',
    '.gitignore': '.dart_tool/\nbuild/\n.flutter-plugins-dependencies\n.scene-tool/write.lock\n',
  };
  for (const [name, content] of Object.entries(files)) writeAtomic(safePath(root, name), content);
  const result = emit(root, example);
  return { directory: root, ...result, next: ['Edit scene.json and lib/custom_scene.dart', 'Install Flutter if needed', 'flutter pub get', 'scene-tool qa scene.json --run'] };
}
